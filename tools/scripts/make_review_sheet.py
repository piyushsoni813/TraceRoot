"""Build docs/root-cause-review.md: for each case, the real fix next to every successful agent run's root cause.

usage: python -I make_review_sheet.py

The reviewer marks one verdict per run. The scorer only compares files, functions and the
breaking commit; whether the explained mechanism is right needs a person.
"""
import glob, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CASES = ["filelock-346", "packaging-638", "attrs-1416", "click-3449", "flask-5160"]
DRIVERS = [
    ("Gemini 3.1 Flash Live (preview)", "gemini-3-1-flash-live-preview"),
    ("Gemini 3.5 Flash Lite", "gemini-3-5-flash-lite"),
    ("Gemini 3.1 Flash Lite", "gemini-3-1-flash-lite"),
    ("Gemini 3.8 Live", "gemini-3-8-live"),
    ("Flash chain (3.8 Flash, 3 Flash, 2.5 Flash)", "gemini-3-8-flash+gemini-3-flash-preview+gemini-2-5-flash"),
]
DIFF_LINES = 60
_AI_PATH = os.path.join(ROOT, "docs", "root-cause-review-ai.json")
AI = {k: v for k, v in json.load(open(_AI_PATH, encoding="utf-8")).items() if not k.startswith("_")} if os.path.exists(_AI_PATH) else {}


def git(upstream, *args):
    return subprocess.run(["git", "-C", upstream, *args], capture_output=True, text=True, errors="replace").stdout


def case_facts(case):
    d = f"{ROOT}/cases/{case}"
    meta = json.load(open(f"{d}/metadata.json", encoding="utf-8"))
    val = json.load(open(f"{d}/reference/validation.json", encoding="utf-8")) if os.path.exists(f"{d}/reference/validation.json") else {}
    fixed = meta.get("fixed_revision") or val.get("reference_revision")
    breaking = meta.get("breaking_commit") or meta["faulty_revision"]
    up = f"{d}/upstream"
    diff = git(up, "diff", "-U2", meta["faulty_revision"], fixed, "--", "src")
    lines = diff.splitlines()
    return {
        "issue": meta.get("issue_url") or val.get("upstream_issue", ""),
        "pr": meta.get("fix_pull_request_url") or val.get("reference_pull_request", ""),
        "breaking": breaking, "breaking_subject": git(up, "log", "-1", "--format=%s", breaking).strip(),
        "files": git(up, "diff", "--name-only", meta["faulty_revision"], fixed, "--", "src").split(),
        "diff": "\n".join(lines[:DIFF_LINES]) + (f"\n... ({len(lines) - DIFF_LINES} more lines)" if len(lines) > DIFF_LINES else ""),
    }


def latest_success(case, slug):
    best = None
    for d in sorted(glob.glob(f"{ROOT}/experiments/{case}-agent-{slug}-?")):
        if os.path.exists(f"{d}/evaluation.json") and json.load(open(f"{d}/evaluation.json"))["repair"]["outcome"] == "success":
            best = d
    return best


out = ["# Root cause review sheet", "",
       "For each case: the real fix first, then every agent run that repaired the bug. The scorer only compares the file,",
       "function and breaking commit. Please read each mechanism and tick one verdict:",
       "",
       "- **correct**: the explanation matches why the real fix was needed",
       "- **partly**: right place, but the explanation is incomplete or partly wrong",
       "- **wrong**: the explanation does not match the real cause, even if the patch happens to pass",
       "",
       "Each run also shows an AI pre-review (from `docs/root-cause-review-ai.json`). It is a starting point only;",
       "your verdict is the one that counts.", "",
       "Generated by `tools/scripts/make_review_sheet.py`. Full reports are in each run's `report.md`.", ""]
total = 0
for case in CASES:
    f = case_facts(case)
    out += [f"## {case}", "",
            f"- Issue: {f['issue']}", f"- Fix pull request: {f['pr']}",
            f"- Breaking commit: `{f['breaking'][:10]}` {f['breaking_subject']}",
            f"- Files changed by the fix: {', '.join(f'`{x}`' for x in f['files'])}", "",
            "<details><summary>Real fix (diff of src/)</summary>", "", "```diff", f["diff"], "```", "", "</details>", ""]
    for label, slug in DRIVERS:
        d = latest_success(case, slug)
        if not d:
            continue
        total += 1
        ev = json.load(open(f"{d}/evaluation.json"))
        rc = json.load(open(f"{d}/report.json"))["root_cause"]
        rel = os.path.relpath(d, ROOT).replace("\\", "/")
        out += [f"### {label}  ({os.path.basename(d)[-1]})", "",
                f"Scorer: **{ev['root_cause']['status']}** (commit match: {ev['root_cause']['commit_match']}, "
                f"file match: {ev['root_cause']['file_match']}, function match: {ev['root_cause']['function_match']})", "",
                f"- File: `{rc.get('file', '')}`", f"- Function: `{rc.get('function', '')}`",
                f"- Breaking commit named: `{rc.get('breaking_commit') or 'none'}`", "",
                "> " + (rc.get("mechanism") or "").replace("\n", "\n> "), "",
                f"Report: [{rel}/report.md]({rel}/report.md)", ""]
        ai = AI.get(os.path.basename(d))
        if ai:
            out += [f"AI pre-review (Claude, not a human verdict): **{ai['verdict']}**. {ai['note']}", ""]
        out += ["Your verdict: [ ] correct   [ ] partly   [ ] wrong", ""]
out.insert(13, f"{total} runs to review across {len(CASES)} cases.\n")
open(f"{ROOT}/docs/root-cause-review.md", "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"wrote docs/root-cause-review.md with {total} runs")
